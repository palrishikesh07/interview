//What is the Event Loop?

/**
 * The Event Loop is the mechanism in Node.js that allows JavaScript to handle asynchronous operations 
 * without blocking the main thread.
 * 
 * Node.js uses a single JavaScript thread to execute JavaScript code, but it can handle many operations such as:
 * 
 * File system operations
 * Network requests
 * Database calls
 * Timers
 * HTTP requests
 * 
 * The Event Loop coordinates these asynchronous operations and decides when their callbacks should execute.
 * 
 */